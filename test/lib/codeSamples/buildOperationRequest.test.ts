import { describe, expect, it } from 'vitest'
import { buildHarRequest } from '../../../src/lib/codeSamples/buildHarRequest'
import { buildOperationRequest } from '../../../src/lib/codeSamples/buildOperationRequest'
import { buildRequest } from '../../../src/lib/codeSamples/buildRequest'

function operationWithContent(content: Record<string, any>): any {
  return { operationId: 'op', requestBody: { content }, responses: {} }
}

function build(operation: any) {
  return buildOperationRequest({ path: '/items', method: 'post', operation, baseUrl: 'https://api.example.com' })
}

describe('buildOperationRequest', () => {
  it('uses the example of the first content type', () => {
    const request = build(operationWithContent({
      'application/xml': { examples: { XML: { value: '<a/>', isAutogenerated: true } } },
      'application/json': { examples: { JSON: { value: { a: 1 }, isAutogenerated: true } } },
    }))

    expect(request.contentType).toBe('application/xml')
    expect(request.body).toBe('<a/>')
  })

  it('leaves the body undefined when the first content type has no example', () => {
    const request = build(operationWithContent({
      'application/octet-stream': {},
      'application/json': { examples: { JSON: { value: { a: 1 }, isAutogenerated: true } } },
    }))

    expect(request.contentType).toBe('application/octet-stream')
    expect(request.body).toBeUndefined()
  })

  it.each([false, 0])('keeps the falsy example %s', (value) => {
    const request = build(operationWithContent({
      'application/json': { examples: { JSON: { value, isAutogenerated: true } } },
    }))

    expect(request.body).toBe(value)
    expect(buildHarRequest(request).postData?.text).toBe(JSON.stringify(value))
  })
})

describe('buildRequest body', () => {
  const base = { path: '/items', method: 'POST' as any, baseUrl: 'https://api.example.com' }

  it.each([false, 0])('sends the falsy body %s', (body) => {
    expect(buildRequest({ ...base, body }).body).toBe(body)
  })

  it.each(['', null, undefined])('skips the empty body %s (playground placeholder)', (body) => {
    const request = buildRequest({ ...base, body })
    expect(request.body).toBeUndefined()
    expect(request.headers['content-type']).toBeUndefined()
  })
})

describe('buildRequest parameter examples', () => {
  const parameters: any[] = [
    { name: 'id', in: 'path', example: 'abc' },
    { name: 'id', in: 'header', example: 'trace123' },
  ]

  it('resolves examples per location', () => {
    const request = buildRequest({ path: '/items/{id}', method: 'GET' as any, baseUrl: 'https://api.example.com', parameters })

    expect(request.url.toString()).toBe('https://api.example.com/items/abc')
    expect(request.headers.id).toBe('trace123')
  })

  it('lets caller variables (keyed by name, as in the playground) win', () => {
    const request = buildRequest({ path: '/items/{id}', method: 'GET' as any, baseUrl: 'https://api.example.com', parameters, variables: { id: 'x' } })

    expect(request.url.toString()).toBe('https://api.example.com/items/x')
    expect(request.headers.id).toBe('x')
  })
})
